// Writes docs/COMMANDS.md from the command registry: `node scripts/gen-commands.mjs`.
// `--check` fails when the file is out of date (used by the tests).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { groups } from '../src/commands/registry.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'docs', 'COMMANDS.md');

const TITLES = { app: 'App', build: 'Build', character: 'Character', tree: 'Passive tree', skills: 'Skills', gems: 'Gems', items: 'Items',
  config: 'Configuration', calc: 'Calculations', notes: 'Notes', ui: 'PoB window', engine: 'Engine' };

const flag = name => `--${name.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`)}`;
const cli = name => name.split('.').map(w => w.replace(/_/g, '-')).join(' ');

export function render() {
  const lines = ['# Command reference', '', '<!-- Generated by scripts/gen-commands.mjs from src/commands/registry.mjs. Do not edit by hand. -->', '',
    'Every command prints one JSON object: `{"ok": true, "target": "live" | "headless" | "app", "result": …}` or `{"ok": false, "error": {"code", "message"}}`.',
    'The same commands are MCP tools named `pob_<group>_<action>` on the service\'s `/mcp` endpoint.', '',
    '`target` tells where the command ran: `live` = the open PoB window, `headless` = PoB AI\'s background copy of the build, `app` = PoB AI itself.', ''];
  const index = [];
  const body = [];
  for (const [group, commands] of groups()) {
    const title = TITLES[group] ?? group;
    index.push(`- [${title}](#${title.toLowerCase().replace(/ /g, '-')})`);
    body.push(`## ${title}`, '');
    for (const c of commands) {
      const positional = (c.args ?? []).filter(a => a.positional).map(a => (a.required ? `<${a.name}>` : `[${a.name}]`));
      body.push(`### \`pob ${[cli(c.name), ...positional].join(' ')}\``, '', c.summary + (c.live ? ' *(needs the PoB window)*' : '') + (c.mutates ? ' *(changes the build)*' : ''), '');
      if (c.details) body.push(c.details, '');
      const options = (c.args ?? []).filter(a => !a.positional);
      if (options.length) {
        body.push('| Option | Type | Description |', '| --- | --- | --- |');
        for (const a of options) {
          const type = a.enum ? a.enum.map(v => `\`${v}\``).join(' \\| ') : a.type;
          body.push(`| \`${flag(a.name)}\`${a.required ? ' (required)' : ''} | ${type} | ${a.description}${a.default !== undefined ? ` (default ${JSON.stringify(a.default)})` : ''} |`);
        }
        body.push('');
      }
      if (c.examples?.length) body.push('```bash', ...c.examples, '```', '');
    }
  }
  return [...lines, ...index, '', ...body].join('\n').replace(/\n{3,}/g, '\n\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== text) { console.error('docs/COMMANDS.md is out of date. Run: node scripts/gen-commands.mjs'); process.exit(1); }
  } else {
    fs.writeFileSync(target, text);
    console.log(`Wrote ${path.relative(root, target)}`);
  }
}
